#!/usr/bin/env python3
"""Symbolically lift the fused WOTS signer's in-place compaction and tail stores."""
from pathlib import Path
import argparse
import re
import os
import subprocess
import tempfile
import runpy

HERE = Path(__file__).resolve().parent
facade = runpy.run_path(str(HERE / "check-platform-facade.py"))
ROOT, LEAN = facade["ROOT"], facade["LEAN"]


def program(tmp, source):
    signer = source.split("fn wots_sign_fused_active", 1)[1]
    four, tail = signer.split("    while active > 0 {", 1)
    compact_start = four.index("        if left[0] == 0 ||")
    compact = four[compact_start:four.index("\n    }", compact_start)]
    tail = tail[tail.index("        let mut k = 0;"):tail.index("\n    }\n}")]
    # Model slicing into the signature as a symbolic (chain,stride) address.
    old, new = "&mut sig[c * N..]", "sig.at(c * N)"
    if tail.count(old) != 1:
        raise ValueError("unexpected signing-tail store address")
    probe = (HERE/"arm-wots/transitions.rs").read_text()
    (tmp/"probe.rs").write_text(probe.replace("// COMPACTION", compact).replace("// TAIL", tail.replace(old,new)))
    subprocess.run(["rustc", tmp/"probe.rs", "-o", tmp/"probe"],check=True)
    lines = subprocess.check_output([tmp/"probe"],text=True).splitlines()
    # One symbolic row covers an arbitrary digest pair, head, chain index and counters.
    # Intern identical rows and traces so the checked projection remains small.
    save = {}
    widths = []
    for w in (16,24,32):
        cases = []
        for count in range(1,5):
            for mask in range(1<<count):
                for phases in range(1<<count):
                    fields, rows, stores = lines.pop(0).split("|")
                    if fields != f"{count} {mask} {phases}":
                        raise ValueError("incomplete lane decision enumeration")
                    def tuples(encoded):
                        return [tuple(map(int, t.split(","))) for t in encoded.split(";") if t]
                    records = tuples(rows)
                    events = tuples(stores)
                    if any(n != w for _,n,_,_ in events):
                        raise ValueError("signature stride differs from the hash width")
                    key = tuple(records), tuple((c,x,xb) for c,_,x,xb in events)
                    cases.append(save.setdefault(key,len(save)))
        widths.append(cases)
    if lines or widths[0] != widths[1] or widths[1] != widths[2]:
        raise ValueError("the width-specialized protocols differ")
    output = ["""-- Generated by scripts/check-arm-wots-transitions.py.
import Armwide.TransitionTypes
namespace slhdsa.Armwide.Transitions
def snapshots : Array Snapshot := #["""]
    def record(xs): return "⟨" + ",".join(map(str,xs)) + "⟩"
    for records, events in save:
        output.append("  ⟨[" + ",".join(map(record,records)) + "],[" + ",".join(map(record,events)) + "]⟩,")
    output.append("]\ndef serial : Array Nat := #[")
    for k in range(0,len(widths[0]),20):
        output.append("  "+",".join(map(str,widths[0][k:k+20]))+",")
    output.append("]\nend slhdsa.Armwide.Transitions\n")
    return "\n".join(output)


def hash_program(tmp, source):
    def function(name):
        start = source.index("fn " + name + "<")
        left = source.index("{", start)
        indent = "    " if name in ("load_heads", "load_shared_head") else ""
        end = source.index("\n" + indent + "}", left) + len(indent) + 2
        return source[start:end].replace("super::K", "K")
    parts = [function(n) for n in ("load_heads", "load_shared_head", "step4_distinct_heads", "run_shared4_steps")]
    # vld1q_u32 loads one whole four-word Head component. The symbolic register
    # represents that component and cannot be used for arithmetic.
    for i in (0,1):
        parts[i] = re.sub(r"vld1q_u32\((head(?:s\[l\])?\.(?:m0|a1|e1))\.as_ptr\(\)\)", r"\1", parts[i])
    signer = source.split("fn wots_sign_fused_active",1)[1]
    tail = signer.split("    while active > 0 {",1)[1].split("        let mut k = 0;",1)[0]
    tail = tail[tail.index("        if active == 3"):]
    mixed = signer.split("            let hdrs = [",1)[1].split("            for l in 0..4",1)[0]
    mixed = "let hdrs = [" + mixed
    shared = signer.split("            run_shared4_steps::<N>(",1)[1].split("            for l in 0..4",1)[0]
    shared = "let min_left = steps; run_shared4_steps::<N>(" + shared
    probe = (HERE/"arm-wots/hash-routes.rs").read_text().replace("// PRODUCTION", "\n".join(parts))
    for key,body in [("TAIL_HASH",tail),("MIXED_HASH",mixed),("SHARED_HASH",shared)]:
        probe = probe.replace("// "+key,body)
    (tmp/"hash.rs").write_text(probe)
    subprocess.run(["rustc", tmp/"hash.rs", "-o", tmp/"hash"],check=True)
    lines = subprocess.check_output([tmp/"hash"],text=True).splitlines()
    tables = []
    for n in (16,24,32):
        values=[]
        for active,steps,shared in [(k,1,False) for k in range(1,5)]+[(4,k,True) for k in range(1,16)]:
            for j in range(active):
                header,ops = lines.pop(0).split("|")
                fields = list(map(int,header.split()))
                if fields[:5] != [n,active,steps,int(shared),j]:
                    raise ValueError("incomplete native hash call trace")
                calls=[]
                for op in ops.split(";"):
                    if op:
                        h,c,t,high = map(int,op.split(","))
                        if bool(high) != (n!=16):
                            raise ValueError("incorrect 128-bit vs full feed-forward selection")
                        # Tagged counter input has stride 32; the maximum step count is 15.
                        calls.append((h,c,(t//32)-1,t%32))
                values.append((fields[-1],tuple(calls)))
        tables.append(values)
    if lines or tables[0]!=tables[1] or tables[1]!=tables[2]:
        raise ValueError("native hash routes differ between digest widths")
    output=["""-- Generated by scripts/check-arm-wots-transitions.py.
import Armwide.TransitionTypes
namespace slhdsa.Armwide.Transitions
def hashes : Array HashTrace := #["""]
    for lane,calls in tables[0]:
        entries=",".join("⟨"+",".join(map(str,c))+"⟩" for c in calls)
        output.append(f"  ⟨{lane},[{entries}]⟩,")
    output.append("]\nend slhdsa.Armwide.Transitions\n")
    return "\n".join(output)


def store_program(tmp, source):
    fn = source[source.index("unsafe fn store_n<"):]
    fn = fn[:fn.index("\n    }")+6]
    fn = fn.replace("dst.as_mut_ptr().add(16)", "&mut dst[16..]").replace("dst.as_mut_ptr()", "dst")
    body = (HERE/"arm-wots/store.rs").read_text().replace("// PRODUCTION",fn)
    (tmp/"store.rs").write_text(body)
    subprocess.run(["rustc","--edition=2021",tmp/"store.rs","-o",tmp/"store"],check=True)
    rows = subprocess.check_output([tmp/"store"],text=True).splitlines()
    if len(rows)!=3:
        raise ValueError("missing native digest width")
    return ("-- Generated by scripts/check-arm-wots-transitions.py.\n"
            "namespace slhdsa.Armwide.Transitions\n"
            "def storeIndices : Nat → List Nat\n" +
            "".join(f"  | {n} => [{line}]\n" for n,line in zip([16,24,32],rows)) +
            "  | _ => []\nend slhdsa.Armwide.Transitions\n")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--refresh", action="store_true")
    args = p.parse_args()
    os.environ["PATH"] = os.pathsep.join([str(Path.home()/".cargo/bin"), str(Path.home()/".elan/bin"), os.environ["PATH"]])
    with tempfile.TemporaryDirectory() as tmp:
        src = (ROOT/"rust/src/sha256/arm_wide.rs").read_text()
        for name, project in [("TransitionProgram",program), ("HashRouteProgram",hash_program), ("StoreProgram",store_program)]:
            body = project(Path(tmp), src)
            dest = LEAN/"Armwide"/(name+".lean")
            if args.refresh:
                dest.write_text(body)
            elif dest.read_text() != body:
                raise ValueError(f"stale native WOTS projection {name}")
    facade["run"](["lake","build","Armwide.Transitions","Armwide.HashRoutes","Armwide.SignStores"],LEAN)
    for module,name in [("Transitions","active_step"),("HashRoutes","register_digest_fips"),("SignStores","retirement_store")]:
        facade["audit_theorems"]("Armwide."+module, ["slhdsa.Armwide.Transitions."+name])


if __name__ == "__main__":
    main()
