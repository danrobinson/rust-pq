#!/usr/bin/env python3
"""Lift Arm single-key WOTS endpoint computation and bind it to its FIPS proof."""

import os
import re
import runpy
import subprocess
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
facade = runpy.run_path(str(HERE / "check-platform-facade.py"))
ROOT, LEAN = facade["ROOT"], facade["LEAN"]


def function(source, name):
    match = re.search(r"(?:unsafe )?fn " + name + r"(?:<|\()", source)
    start = match.start()
    indent = re.match(r" *", source[source.rfind("\n", 0, start) + 1 : start])[0]
    close = "\n" + indent + "}"
    return source[start : source.index(close, start) + len(close)]


def endpoints(source, directory):
    helpers = [
        function(source, n)
        for n in ("load_shared_head", "step4_shared_head", "run_shared4_steps")
    ]
    helpers[0] = re.sub(
        r"vld1q_u32\((head\.(?:m0|a1|e1))\.as_ptr\(\)\)", r"\1", helpers[0]
    )
    native = function(source, "wots_endpoints_1_active").replace(
        "msg: &mut [u8]", "msg: &mut [usize]"
    )
    parts = (HERE / "arm-wots/hash-routes.rs").read_text().split("// PRODUCTION", 1)[0]
    parts += (
        (HERE / "arm-keygen/endpoints.rs")
        .read_text()
        .replace(
            "// PRODUCTION", "\n".join([*helpers, native]).replace("super::K", "K")
        )
    )
    probe = directory / "arm-endpoints.rs"
    probe.write_text(parts)
    subprocess.run(
        ["rustc", "--edition=2021", probe, "-o", directory / "arm-endpoints"],
        check=True,
    )
    lines = subprocess.check_output(
        [directory / "arm-endpoints"], text=True
    ).splitlines()
    signatures = {}
    words = []
    for n in (16, 24, 32):
        group = []
        for i in range(2 * n + 3):
            metadata, ops = lines.pop(0).split("|")
            width, off, origin = map(int, metadata.split())
            if n != width:
                raise ValueError("missing width-specialized endpoint")
            pattern = tuple(
                (h, c - i, t)
                for h, c, t in (map(int, x.split(",")) for x in ops.split(";") if x)
            )
            group.append(
                f"⟨{off},{origin},{signatures.setdefault(pattern, len(signatures))}⟩"
            )
        words.append(group)
    if lines:
        raise ValueError("unexpected extra endpoint write")
    trace = [
        "#["
        + ",".join(
            "[" + ",".join(f"⟨{h},{c},{t}⟩" for h, c, t in ops) + "]"
            for ops in signatures
        )
        + "]"
    ]
    rows = ["#[" + ",".join("#[" + ",".join(group) + "]" for group in words) + "]"]
    return "\n".join(
        [
            "-- Generated by scripts/check-arm-keygen.py.",
            "namespace slhdsa.Armwide.Keygen",
            "structure Call where\n  head : Nat\n  chainDelta : Int\n  counter : Nat\n  deriving DecidableEq, Inhabited",
            "structure Write where\n  offset : Nat\n  origin : Nat\n  trace : Nat\n  deriving DecidableEq, Inhabited",
            "def traces : Array (List Call) := " + trace[0],
            "def stores : Array (Array Write) := " + rows[0],
            "end slhdsa.Armwide.Keygen",
            "",
        ]
    )


def padding(directory):
    native = function((ROOT / "rust/src/wots/arm.rs").read_text(), "compress_tlen_1")
    if native.count(").to_be_bytes()") != 2 or native.count("buf[size] = 0x80;") != 1:
        raise ValueError("unknown width or location for WOTS hash padding")
    native = native.replace("[u8", "[Byte").replace("[0u8;", "[Byte::Literal(0);")
    native = native.replace("buf[size] = 0x80;", "buf[size] = Byte::Literal(128);")
    native = native.replace(").to_be_bytes()", ").to_be_bytes().map(Byte::Literal)")
    probe = directory / "keygen-padding.rs"
    probe.write_text(
        (HERE / "arm-keygen/padding.rs").read_text().replace("// PRODUCTION", native)
    )
    subprocess.run(
        ["rustc", "--edition=2021", probe, "-o", directory / "keygen-padding"],
        check=True,
    )
    lines = subprocess.check_output(
        [directory / "keygen-padding"], text=True
    ).splitlines()
    programs, kernels = {}, []
    for flag in (0, 1):
        choices = []
        for n in (16, 24, 32):
            key, ops, bytes_ = lines.pop(0).split("|")
            if key != f"{n} {flag}":
                raise ValueError("missing compression route")
            data = list(map(int, bytes_.rstrip(",").split(",")))
            # Compress consecutive identical sources into (start, length, stride) runs.
            chunks = []
            while data:
                start = data[0]
                stride = (
                    data[1] - start
                    if len(data) > 1 and data[1] - start in (0, 1)
                    else 0
                )
                k = 1
                while (
                    k < len(data)
                    and data[k] == start + k * stride
                    and (data[k] // 256 if data[k] < 512 else 2)
                    == (start // 256 if start < 512 else 2)
                ):
                    k += 1
                chunks.append(f"⟨{start},{k},{stride}⟩")
                del data[:k]
            program = "[" + ",".join(chunks) + "]"
            if n in programs and programs[n] != program:
                raise ValueError("padding depends on CPU route")
            programs[n] = program
            choices.append(
                "[" + ",".join("(" + op + ")" for op in ops.split(";") if op) + "]"
            )
        kernels.append("[" + ",".join(choices) + "]")
    if lines:
        raise ValueError("extra public-key compression traces")
    return "\n".join(
        [
            "-- Generated by scripts/check-arm-keygen.py.",
            "namespace slhdsa.Armwide.Keygen",
            "structure Span where\n  source : Nat\n  count : Nat\n  stride : Nat\n  deriving DecidableEq, Inhabited",
            "def spans : List (List Span) := [" + ",".join(programs.values()) + "]",
            "def calls : List (List (List (Nat × Nat))) := [" + ",".join(kernels) + "]",
            "end slhdsa.Armwide.Keygen",
            "",
        ]
    )


def multi(source, directory):
    native = function(source, "compress_multi_1_active").replace(
        "msg: &[u8]", "msg: &[usize]"
    )
    native = native.replace("out.as_mut_ptr()", "&mut out").replace("super::K", "K")
    probe = directory / "multi.rs"
    probe.write_text(
        (HERE / "arm-keygen/multi.rs").read_text().replace("// PRODUCTION", native)
    )
    subprocess.run(
        ["rustc", "--edition=2021", probe, "-o", directory / "multi"], check=True
    )
    blocks = subprocess.check_output([directory / "multi"], text=True).splitlines()
    return (
        "-- Generated by scripts/check-arm-keygen.py.\nnamespace slhdsa.Armwide.Keygen\n"
        "def blocks : List (List Nat) := ["
        + ",".join("[" + line + "]" for line in blocks)
        + "]\n"
        "end slhdsa.Armwide.Keygen\n"
    )


def check_wrappers(target, directory):
    common = facade["common"]
    declarations, body = common["declarations"], common["body"]
    shared = set(declarations(body(LEAN / "Slhdsa/Funs.lean")))
    types = set(declarations(body(LEAN / "Slhdsa/Types.lean")))
    for name, model, root, cuts in [
        (
            "WKey",
            "KeygenProgram",
            "wots::arm::pk_gen",
            ["wots::arm::compress_tlen_1", "sha256::arm_wide::wots_endpoints_1"],
        ),
        (
            "WDispatch",
            "KeyDispatch",
            "wots::wots_pk_gen",
            [
                "sha256::arm_wide::available",
                "wots::arm::pk_gen",
                "wots::sk_blocks",
                "hash::chain_blocks",
                "hash::thash_values",
            ],
        ),
    ]:
        package = facade["extract"](
            "rust",
            target,
            name,
            directory,
            ["crate::" + root],
            ["crate::" + s for s in cuts],
        )
        fresh = set(declarations(body(package / "Funs.lean")))
        model_text = (LEAN / "Armwide" / (model + ".lean")).read_text()
        selected = [
            s for s in fresh if s.startswith("def " + root.replace("::", ".") + "\n")
        ]
        if len(selected) != 1 or selected[0] not in model_text:
            raise ValueError(f"{target}: stale native {root} body")
        for d in fresh - shared:
            if d not in model_text:
                raise ValueError(
                    f"{target}: unmatched dependency in {model}: {d[:100]}"
                )
        if set(declarations(body(package / "Types.lean"))) - types:
            raise ValueError(f"{target}: unexpected type in {model}")
    print(f"{target}: checked Arm WOTS public-key wrapper and dispatcher", flush=True)


def check_guards(source):
    for name, block in [
        (
            "wots_endpoints_1",
            "debug_assert!(available());unsafe{wots_endpoints_1_active::<N>(state,sk_seed,adrs,msg)};",
        ),
        (
            "compress_multi_1",
            "debug_assert!(available()&&!msg.is_empty()&&msg.len()%64==0);unsafe{compress_multi_1_active(state,msg)}",
        ),
    ]:
        code = function(source, name).split("{", 1)[1].rsplit("}", 1)[0]
        if re.sub(r"\s+", "", re.sub(r"//[^\n]*", "", code)) != block:
            raise ValueError(f"unexpected forwarding wrapper for {name}")
    for file, literal in [
        ("address", "WOTS_HASH: u32 = 0"),
        ("address", "WOTS_PK: u32 = 1"),
        ("address", "WOTS_PRF: u32 = 5"),
        ("params", "LEN2: usize = 3"),
    ]:
        if (
            "pub const " + literal + ";"
            not in (ROOT / "rust/src" / (file + ".rs")).read_text()
        ):
            raise ValueError(f"stale probe constant {literal}")


def check(refresh=False):
    os.environ["PATH"] = os.pathsep.join(
        [
            str(Path.home() / ".cargo/bin"),
            str(Path.home() / ".elan/bin"),
            os.environ["PATH"],
        ]
    )
    with tempfile.TemporaryDirectory() as directory:
        source = (ROOT / "rust/src/sha256/arm_wide.rs").read_text()
        check_guards(source)
        for name, fresh in [
            ("EndpointProgram", endpoints(source, Path(directory))),
            ("PaddingProgram", padding(Path(directory))),
            ("MultiProgram", multi(source, Path(directory))),
        ]:
            path = LEAN / "Armwide" / (name + ".lean")
            if refresh:
                path.write_text(fresh)
            elif fresh != path.read_text():
                raise ValueError(f"stale Arm WOTS keygen projection {name}")

        for target in facade["TARGETS"][:2]:
            check_wrappers(target, Path(directory))
    facade["run"](["lake", "build", "Armwide.KeyDispatch"], LEAN)
    facade["audit_theorems"](
        "Armwide.KeyDispatch",
        [
            "slhdsa.Armwide.Keygen." + n
            for n in [
                "written",
                "compression_T",
                "compress_tlen_spec",
                "pk_gen_spec",
                "pk_gen_eq_scalar",
                "Dispatcher.dispatch_eq_scalar",
            ]
        ],
    )


if __name__ == "__main__":
    import argparse

    p = argparse.ArgumentParser()
    p.add_argument("--refresh", action="store_true")
    check(p.parse_args().refresh)
