#!/bin/sh
# Generate lean/Ct/Funs.lean (the leakage-instrumented program) from lean/Slhdsa/Funs.lean.
#
# Only the header and the closing `end` change: imports, the namespace (`slhdsa` becomes
# `slhdsa_leak`) and what is opened. Every other line is copied verbatim; inside
# `namespace slhdsa_leak` the names used by the text resolve to the instrumented primitives
# of lean/Ct/Model.lean. The script fails if the source header is not exactly the expected one,
# and checks afterwards that the body is byte-for-byte identical.
set -e
cd "$(dirname "$0")/.."
python3 -I - lean/Slhdsa/Funs.lean lean/Ct/Funs.lean <<'EOF'
import sys
src_path, dst_path = sys.argv[1], sys.argv[2]
src = open(src_path).read().split('\n')

# The header Aeneas writes (lines up to and including `namespace slhdsa`).
expected_header = [
    "-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS",
    "-- [slhdsa]: function definitions",
    "module",
    "public import Aeneas",
    "public import Slhdsa.Types",
    "@[expose] public section",
    "open Aeneas Aeneas.Std Result ControlFlow Error",
]
for i, line in enumerate(expected_header):
    if src[i] != line:
        sys.exit(f"ct-gen: unexpected header line {i+1}: {src[i]!r} (expected {line!r})")
ns = src.index("namespace slhdsa")
# Lines between the `open` and the namespace are `set_option`s, comments and blanks.
for line in src[len(expected_header):ns]:
    if line and not (line.startswith("set_option ") or line.startswith("/-")):
        sys.exit(f"ct-gen: unexpected line in header: {line!r}")
# The file ends with `end slhdsa` (and a trailing newline).
last = max(i for i, l in enumerate(src) if l.strip())
if src[last] != "end slhdsa":
    sys.exit(f"ct-gen: unexpected last line {src[last]!r}")
body = src[ns + 1:last]
if any(l.strip() in ("namespace slhdsa", "end slhdsa") for l in body):
    sys.exit("ct-gen: nested namespace slhdsa in the body")

new_header = [
    "-- GENERATED BY scripts/ct-gen.sh FROM lean/Slhdsa/Funs.lean. DO NOT EDIT.",
    "-- Only this header and the final `end` differ from the source: the definitions below are",
    "-- the verified program's text, elaborated in `namespace slhdsa_leak`, where the names it",
    "-- uses resolve to the instrumented primitives of `Ct/Model.lean`.",
    "import Ct.Model",
    "import Slhdsa.Types",
    "open Aeneas Aeneas.Std Result ControlFlow Error",
    "open slhdsa",
]
out = new_header + src[len(expected_header):ns] + ["namespace slhdsa_leak"] + body + \
      ["end slhdsa_leak"] + src[last + 1:]
open(dst_path, "w").write('\n'.join(out))

# Self-check: the body is identical.
gen = open(dst_path).read().split('\n')
gns = gen.index("namespace slhdsa_leak")
glast = max(i for i, l in enumerate(gen) if l.strip())
assert gen[gns + 1:glast] == body, "ct-gen: body differs"
print(f"ct-gen: wrote {dst_path} ({len(body)} body lines copied verbatim)")
EOF
