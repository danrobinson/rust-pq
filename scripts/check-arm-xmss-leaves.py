#!/usr/bin/env python3
"""Lift the Arm fused WOTS endpoint schedules used by the XMSS leaf batches."""

import argparse
import os
from pathlib import Path
import re
import runpy
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent
keygen = runpy.run_path(str(HERE / "check-arm-keygen.py"))
function, ROOT, LEAN = keygen["function"], keygen["ROOT"], keygen["LEAN"]


def endpoints(directory):
    source = (ROOT / "rust/src/sha256/arm_wide.rs").read_text()
    helpers = [
        function(source, n)
        for n in (
            "load_shared_head",
            "load_heads",
            "step4_shared_head",
            "run_shared4_steps",
            "step4_distinct_heads",
            "step4_wots_prf",
            "run_wots4_15steps",
            "run_wots2_15steps",
            "wots_endpoints_2_active",
            "wots_endpoints_4_active",
        )
    ]
    body = "\n".join(helpers).replace("super::K", "K")
    body = re.sub(
        r"vld1q_u32\(((?:heads\[l\]|head)\.(?:m0|a1|e1))\.as_ptr\(\)\)", r"\1", body
    )
    body = body.replace("first: u32", "first: Keypair").replace(
        "msgs: &mut [[u8; L]", "msgs: &mut [[Cell; L]"
    )
    parts = (HERE / "arm-wots/hash-routes.rs").read_text().split("// PRODUCTION", 1)[0]
    probe = directory / "batched.rs"
    probe.write_text(
        parts
        + (HERE / "arm-keygen/batched.rs").read_text().replace("// PRODUCTION", body)
    )
    subprocess.run(
        ["rustc", "--edition=2021", probe, "-o", directory / "batched"], check=True
    )
    raw = subprocess.check_output([directory / "batched"], text=True).splitlines()
    schedules = {}
    configurations = []
    for n, l, g in [
        (n, l, g) for n, l in [(16, 640), (24, 1280), (32, 2304)] for g in (2, 4)
    ]:
        if raw.pop(0) != f"GROUP {n} {l} {g}":
            raise ValueError("batch origin mismatch")
        rows = []
        for i in range(g * (2 * n + 3)):
            metadata, trace = raw.pop(0).split("|")
            dst, sk = map(int, metadata.split())
            lane, offset = divmod(dst, l)
            chain = (offset - 22) // n
            # Order does not affect the final memory only when destination intervals
            # are disjoint. The universal Lean shape proof below checks that fact.
            ops = tuple(
                (h // 8 - lane, h % 8, c - chain, t)
                for h, c, t in (map(int, s.split(",")) for s in trace.split(";") if s)
            )
            rows.append((lane, offset, sk, schedules.setdefault(ops, len(schedules))))
        rows.sort()
        configurations.append(
            "#["
            + ",".join(
                f"⟨{lane},{off},{origin},{seq}⟩" for lane, off, origin, seq in rows
            )
            + "]"
        )
    if raw:
        raise ValueError("extra endpoint writes")
    return "\n".join(
        [
            "-- Generated by scripts/check-arm-xmss-leaves.py.",
            "namespace slhdsa.Armwide.XmssLeaves",
            "structure Operation where\n  keyDelta : Int\n  tag : Nat\n  chainDelta : Int\n  counter : Nat\n  deriving DecidableEq, Inhabited",
            "structure Write where\n  lane : Nat\n  offset : Nat\n  origin : Nat\n  trace : Nat\n  deriving DecidableEq, Inhabited",
            "def traces : Array (List Operation) := #["
            + ",".join(
                "[" + ",".join(f"⟨{k},{h},{c},{t}⟩" for k, h, c, t in ops) + "]"
                for ops in schedules
            )
            + "]",
            "def writes : Array (Array Write) := #[" + ",".join(configurations) + "]",
            "end slhdsa.Armwide.XmssLeaves",
            "",
        ]
    )


def multi(directory):
    src = (ROOT / "rust/src/sha256/arm_wide.rs").read_text()
    body = "\n".join(
        function(src, k)
        for k in ["compress_block_lanes_in_place", "compress_multi_lanes"]
    )
    body = (
        body.replace("super::K", "K")
        .replace("msgs: &[[u8; L]", "msgs: &[[usize; L]")
        .replace("out: &mut [[u8; 16]]", "out: &mut [[u32; 16]]")
    )
    source = directory / "multibatch.rs"
    source.write_text(
        (HERE / "arm-keygen/batched-multi.rs")
        .read_text()
        .replace("// PRODUCTION", body)
    )
    subprocess.run(
        ["rustc", "--edition=2021", source, "-o", directory / "multibatch"], check=True
    )
    raw = subprocess.check_output([directory / "multibatch"], text=True).splitlines()
    rows = []
    for g in (2, 4):
        lanes = []
        for k in range(g):
            tag, steps = raw.pop(0).split("|")
            if tag != f"{g} {k}":
                raise ValueError("bad digest store")
            blocks = [
                "[" + step.rstrip(",") + "]" for step in steps.rstrip(";").split(";")
            ]
            lanes.append("[" + ",".join(blocks) + "]")
        rows.append("[" + ",".join(lanes) + "]")
    if raw:
        raise ValueError("extra SHA-256 XMSS digest")
    return (
        "-- Generated by scripts/check-arm-xmss-leaves.py.\nnamespace slhdsa.Armwide.XmssLeaves\n"
        "def reads : List (List (List (List Nat))) := ["
        + ",".join(rows)
        + "]\nend slhdsa.Armwide.XmssLeaves\n"
    )


def fill(directory):
    src = (ROOT / "rust/src/xmss/arm.rs").read_text()
    parts = []
    for name, n in [("batch_root_16", "16"), ("batch_root_512", "N")]:
        original = function(src, name)
        before, tail = original.split("    for level in 1..=height {", 1)
        if not tail.rstrip().endswith("roots[0]\n}"):
            raise ValueError(
                "unexpected handoff from native leaves to parent reductions"
            )
        lifted = (
            before.replace("index: u32", "index: Base")
            .replace("-> [u8; " + n + "]", "-> [[Byte; " + n + "]; 16]")
            .replace("[0u8;", "[Byte::Zero;")
        )
        parts.append(lifted + "    roots\n}")
    source = directory / "fill.rs"
    source.write_text(
        (HERE / "arm-keygen/leaf-fill.rs")
        .read_text()
        .replace("// PRODUCTION", "\n".join(parts))
    )
    subprocess.run(
        ["rustc", "--edition=2021", source, "-o", directory / "fill"], check=True
    )
    raw = subprocess.check_output([directory / "fill"], text=True).splitlines()
    configs = []
    for n in (16, 24, 32):
        heights = []
        for h in range(1, 5):
            header, data = raw.pop(0).split("|")
            if header != f"{n} {h}":
                raise ValueError("unexpected leaf table")
            rows = [
                "none" if r == "-" else "(some ⟨" + r + "⟩)"
                for r in data.rstrip(";").split(";")
            ]
            heights.append("#[" + ",".join(rows) + "]")
        configs.append("#[" + ",".join(heights) + "]")
    if raw:
        raise ValueError("extra subtree height")
    return (
        "-- Generated by scripts/check-arm-xmss-leaves.py.\nnamespace slhdsa.Armwide.XmssLeaves\n"
        "structure Slot where\n  headerShift : Nat\n  headerOffset : Nat\n  baseShift : Nat\n  baseOffset : Nat\n  groupSize : Nat\n  lane : Nat\n  deriving DecidableEq, Inhabited\n"
        "def slots : Array (Array (Array (Option Slot))) := #["
        + ",".join(configs)
        + "]\nend slhdsa.Armwide.XmssLeaves\n"
    )


def check_wide(directory):
    src = (ROOT / "rust/src/xmss/arm.rs").read_text()
    body = "\n".join(
        function(src, name) for name in ["compress_tlen_pair", "compress_tlen_quad"]
    ).replace("[u8;", "[Byte;")
    rust = directory / "wide.rs"
    rust.write_text(
        (HERE / "arm-keygen/leaf-wide.rs").read_text().replace("// PRODUCTION", body)
    )
    subprocess.run(
        ["rustc", "--edition=2021", rust, "-o", directory / "wide"], check=True
    )
    subprocess.run([directory / "wide"], check=True)


def check_forwarders():
    source = (ROOT / "rust/src/sha256/arm_wide.rs").read_text()
    for g in (2, 4):
        for name, wanted in [
            (
                f"wots_endpoints_{g}",
                f"debug_assert!(available());unsafe{{wots_endpoints_{g}_active::<N,L>(state,sk_seed,adrs,first,msgs)}};",
            ),
            (
                f"compress_multi_{g}",
                f"debug_assert!(available()&&L>0&&L%64==0&&out.len()>={g});unsafe{{compress_multi_lanes::<{g},L>(state,msgs,out)}};",
            ),
        ]:
            body = function(source, name).split("{", 1)[1].rsplit("}", 1)[0]
            if re.sub(r"\s+", "", re.sub(r"//[^\n]*", "", body)) != wanted:
                raise ValueError("unrecognized batched forwarding wrapper " + name)


def check_dispatch(target, directory):
    facade = keygen["facade"]
    parent = runpy.run_path(str(HERE / "check-arm-xmss-parents.py"))
    package = facade["extract"](
        "rust",
        target,
        "ArmXmss",
        directory,
        ["crate::xmss::arm::batch_root"],
        parent["cuts"],
    )
    fresh = parent["declarations"](package / "Funs.lean", "slhdsa")
    entry = [d for d in fresh if d.startswith("def xmss.arm.batch_root\n")]
    if len(entry) != 1 or entry[0] not in (LEAN / "Armwide/XmssBatch.lean").read_text():
        raise ValueError(f"{target}: outer Arm XMSS dispatch differs")
    if set(parent["declarations"](package / "Types.lean", "slhdsa")) - set(
        parent["declarations"](LEAN / "Slhdsa/Types.lean", "slhdsa")
    ):
        raise ValueError(f"{target}: Arm XMSS type layouts differ")
    print(f"{target}: Aeneas batch_root dispatch and layouts match", flush=True)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--refresh", action="store_true")
    args = parser.parse_args()
    os.environ["PATH"] = os.pathsep.join(
        [
            str(Path.home() / ".cargo/bin"),
            str(Path.home() / ".elan/bin"),
            os.environ["PATH"],
        ]
    )
    with tempfile.TemporaryDirectory() as tmp:
        check_forwarders()
        check_wide(Path(tmp))
        for name, build in [
            ("XmssLeavesProgram", endpoints),
            ("XmssMultiProgram", multi),
            ("XmssFillProgram", fill),
        ]:
            fresh = build(Path(tmp))
            path = LEAN / "Armwide" / (name + ".lean")
            if args.refresh:
                path.write_text(fresh)
            elif path.read_text() != fresh:
                raise ValueError("stale Arm XMSS leaf projection " + name)

        for target in keygen["facade"]["TARGETS"][:2]:
            check_dispatch(target, Path(tmp))
    facade = keygen["facade"]
    facade["run"](["lake", "build", "Armwide.XmssBatch"], LEAN)
    facade["audit_theorems"](
        "Armwide.XmssBatch",
        [
            "slhdsa.Armwide.XmssLeaves." + s
            for s in [
                "endpoint_fips",
                "payload_fips",
                "batched256_eq",
                "batched512_eq",
                "prepare_spec",
                "leafValue",
                "sourceRow_prepared",
                "fill_correct",
                "small_root",
                "large_root",
                "batch_root_fips",
                "batch_root_eq_scalar",
            ]
        ],
    )


if __name__ == "__main__":
    main()
