import re,sys
SRC='/Users/danrobinson/Projects/formal-sig/security/Reduction/'
OUT='/Users/danrobinson/Projects/formal-sig/multi/security/MReduction/'
files=['HeadlineFinal','TcrMemoHeadline','Linear','LinearBytes','TightCapsHeadline','HeadlineSplit','Bytes']
SETS=[('128s','s128s',16),('128f','s128f',16),('192s','s192s',24),('192f','s192f',24),('256s','s256s',32),('256f','s256f',32)]
thms=[]  # (file, origname, newbase, text)
for f in files:
    s=open(SRC+f+'.lean').read()
    for m in re.finditer(r'^theorem (slhdsa_\w*128s\w*)\n(.*?)\n\n', s, re.S|re.M):
        name=m.group(1); body=m.group(2)
        if 'structural_128s' not in body: print('SKIP',f,name,file=sys.stderr); continue
        if name.startswith('slhdsa_sha2_128s_'): base=name[len('slhdsa_sha2_128s_'):]
        else:
            assert name.endswith('_128s'); base=name[len('slhdsa_'):-len('_128s')]
        thms.append((f,name,base,body))
names=[t[2] for t in thms]; assert len(set(names))==len(names),names
print(len(thms),file=sys.stderr)
def tr(body,setexpr):
    b=re.sub(r'\bS\b','F',body)
    b=b.replace('Link.vp','§.vp').replace('Link.prims','§.prims').replace('codec128s','(codec §)').replace('structural_128s','(structural §)')
    assert 'Link.' not in b and '128' not in b, b
    return b.replace('§',setexpr)
def kind(base):
    k=[]
    k.append('SUF-CMA' if 'suf' in base else 'EUF-CMA')
    k.append('external pure interface (FIPS 205 Alg. 21/22/24)' if 'pure' in base else 'internal algorithms (FIPS 205 Alg. 18–20)')
    k.append('byte-string keys, messages, signatures' if 'bytes' in base else 'typed keys and signatures')
    if 'deterministic' in base: k.append('uniform `PK.seed`, deterministic signing (`opt_rand = PK.seed`)')
    if 'hedged' in base: k.append('uniform `PK.seed`, hedged signing (`opt_rand` uniform, fresh per signature)')
    if 'linear' in base: k.append('linear form (real-world probabilities right, ideal-world left)')
    elif 'tight' in base: k.append('tight caps, re-capped class adversaries `bTcrArST` (superseded by the `_final`/`_final_memo` forms)')
    elif 'split' in base: k.append('loose caps `tcrTargets` (superseded)')
    elif 'final' in base or 'deterministic' in base or 'hedged' in base: k.append('final form: twelve standard-model advantages, tight caps, memoising class adversaries `bTcrArM`')
    else: k.append('split bound `betaSufFinalSplit`/`betaEufFinalSplit` (superseded)')
    return '; '.join(k)
def funcs(n,short):
    if n==16:
        return ("Functions of the twelve terms at this set (`n = 16`): everything is SHA-256 — `PRF`, `F`, `H`, `T_len`, `T_k` are\n"
          "`Trunc_16(SHA-256(PK.seed ‖ 0^48 ‖ ADRSc ‖ ·))`, `PRF_msg` is HMAC-SHA-256, `H_msg` is MGF1-SHA-256 over an inner\n"
          "SHA-256 (`MReduction.thash_class`, `fHash_eval`, `prf_spec`, `prfMsg_spec`, `hmsg_spec` in `MReduction/Audit.lean`).")
    return ("Functions of the twelve terms at this set (`n = %d`): `PRF` and every `F` game (FORS-leaf DSPR/TCR, class `1`, WOTS\n"
          "UD/PRE/chain-TCR) are `Trunc_%d(SHA-256(PK.seed ‖ 0^%d ‖ ADRSc ‖ ·))`; the class games `2` (`H`), `len` (`T_len`), `k` (`T_k`)\n"
          "are `Trunc_%d(SHA-512(PK.seed ‖ 0^%d ‖ ADRSc ‖ ·))`; `PRF_msg` is HMAC-SHA-512; ITSR is about `H_msg` = MGF1-SHA-512\n"
          "over an inner SHA-512.  The collection oracle of every SM game is the whole `Thash` (both hash functions).\n"
          "See `MReduction.thash_class`, `thash_class_sha512`, `fHash_eval`, `prf_spec`, `prfMsg_spec`, `hmsg_spec`\n(`MReduction/Audit.lean`).")%(n,n,64-n,n,128-n)
