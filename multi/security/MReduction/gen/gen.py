def emit(fname,title,sel):
    o=[hdr%(title,', '.join('`%s.lean`'%f for f in sorted(set(t[0] for t in sel))))]
    ax=[]
    for (f,name,base,body) in sel:
        o.append('/-- **%s of SLH-DSA at any SHA-2 parameter set `S`** — %s.\nInstance of `Reduction.%s` (`Reduction/%s.lean`).  Which hash function each term is about depends on `S`:\nsee the per-set theorems and `MReduction/Audit.lean`. -/'%(kind(base).split(';')[0],'; '.join(kind(base).split('; ')[1:]),name,f))
        o.append('theorem slhdsa_sha2_%s (S : Sha2Set)\n%s\n'%(base,tr(body,'S')))
        ax.append('slhdsa_sha2_%s'%base)
    for (sn,sc,n) in SETS:
        o.append('/-! ## SLH-DSA-SHA2-%s -/\n'%sn)
        for (f,name,base,body) in sel:
            o.append('/-- **%s of SLH-DSA-SHA2-%s** — %s.\n%s -/'%(kind(base).split(';')[0],sn,'; '.join(kind(base).split('; ')[1:]),funcs(n,sn)))
            o.append('theorem slhdsa_sha2_%s_%s\n%s\n'%(sn,base,tr(body,'Sha2Set.'+sc)))
            ax.append('slhdsa_sha2_%s_%s'%(sn,base))
    o.append('\n'.join('#print axioms '+a for a in ax))
    o.append('\nend MReduction\n')
    open(OUT+fname,'w').write('\n'.join(o))
