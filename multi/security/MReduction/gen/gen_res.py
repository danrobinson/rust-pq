    v={}
    ln=2*n+3; v['len']=ln
    v['trees']=sum((2**hp)**i for i in range(d)); v['inst']=v['trees']*2**hp
    v['open']=2**h*k*2**a; v['chain']=v['inst']*ln; v['step']=v['chain']*16; v['exec']=v['chain']*15
    v['tcr']=v['open']+2**h*k*(2**a-1)+2**h+v['exec']+v['inst']+(2**h-1)
    v['ar1']=v['open']+v['exec']; v['ar2']=2**h*k*(2**a-1)+v['trees']*(2**hp-1); v['arLen']=v['inst']; v['arK']=2**h
    assert v['ar1']+v['ar2']+v['arLen']+v['arK']==v['tcr']
    v['prf']=v['open']+v['chain']
    v['kg']=2**hp*(ln*15+2)
    v['sign']=1+k*(2**a*2)+(k*(1+a)+1)+d*(2**hp*(ln*15+2)+(ln*15+1+hp))
    v['ver']=k*(1+a)+1+d*(ln*15+1+hp)
    v['fsign']=1+k*(2**a-1)+(k*(1+a)+1)+d*(2**hp*(ln*15+2)+(ln*15+1+hp))
    v['hist']=1+k*(2**a*2)+d*(2**hp*2)
    v['win']=ln*15; v['pre']=ln*16; v['wtcr']=ln*(15*32)
    v['sreads']=k*2**a+d*(2**hp*ln); v['kreads']=2**hp*ln
    v['memo']=1+v['ver']*2
    return v
