import re, sys
root = sys.argv[1]
FUNS = ['slhKeygenInternal','slhSignInternalChecked','slhSignChecked','slhSignInternal',
        'slhVerifyInternal','slhSign','slhVerify','block','skPk','KeyOk']
SKIP = {'bytes_lengthN','verify_eq','blockSeed_length','ok_inj'}

def section(path):
    t = open(path).read()
    a = t.index('namespace sha2_128s'); b = t.index('end sha2_128s', a)
    return t[a:b]

def theorems(sec):
    out = []
    for m in re.finditer(r'^theorem (\S+)(.*?):=', sec, re.S | re.M):
        name, rest = m.group(1), m.group(2)
        if name in SKIP: continue
        # split binders / type at the top-level colon
        depth = 0
        for i, c in enumerate(rest):
            if c in '([{⟨': depth += 1
            elif c in ')]}⟩': depth -= 1
            elif c == ':' and depth == 0: break
        binders, ty = rest[:i].strip(), rest[i+1:].strip()
        out.append((name, binders, ty))
    return out

def conv(ty):
    used = []
    for f in FUNS:
        pat = f'Spec.{f} Spec.sha2_128s'
        if pat in ty:
            used.append(f); ty = ty.replace(pat, f'Spec128.{f}')
    assert 'sha2_128s.n' not in ty and 'Spec.sha2_128s' not in ty, ty
    return ty, used

body = []
for path in ['Slhdsa/Theorems.lean', 'Slhdsa/ApiTheorems.lean']:
    body.append(f'\n/-! ### From `{path}` -/\n')
    for name, binders, ty in theorems(section(f'{root}/{path}')):
        ty2, used = conv(ty)
        binders, used2 = conv(binders)
        used = [f for f in FUNS if f in used or f in used2]
        if not used:
            body.append(f'-- `{name}` mentions no function of the specification.\n')
            continue
        rws = ', '.join(f'← Spec128.{f}_eq' for f in used)
        bind = f'∀ {binders}, ' if binders else ''
