ax=[]
def binders(se): return f'    (optRand : PublicKeyCore {se}.prims.core → ProbComp {se}.prims.Y)\n    (pkSeedDist : ProbComp {se}.prims.PkSeed)\n'
for nm,stmt in sel:
    base=nm[len('slhdsa_'):]
    var='F' if 'suf' in nm else 'A'
    o.append(f'/-- `Reduction.{nm}` at any SHA-2 parameter set `S` (twelve terms written out). -/\ntheorem slhdsa_sha2_{base}_explicit (S : Sha2Set)\n{binders("S")}{tr(stmt,"S")} :=\n  {nm} (structural S) {var}\n')
    ax.append(f'slhdsa_sha2_{base}_explicit')
for sn,sc,n in SETS:
    o.append(f'/-! ## SLH-DSA-SHA2-{sn} -/\n')
    for nm,stmt in sel:
        base=nm[len('slhdsa_'):]
        var='F' if 'suf' in nm else 'A'
        se='Sha2Set.'+sc
        kind=('SUF-CMA' if 'suf' in nm else 'EUF-CMA')+' of SLH-DSA-SHA2-'+sn+(', external pure interface (FIPS 205 Alg. 21/22/24)' if 'pure' in nm else ', internal algorithms (FIPS 205 Alg. 18–20)')+', on byte strings'
        o.append(f'/-- **{kind} — final form, twelve terms written out.**\n{funcs(n)} -/\ntheorem slhdsa_sha2_{sn}_{base}_explicit\n{binders(se)}{tr(stmt,se)} :=\n  {nm} (structural {se}) {var}\n')
        ax.append(f'slhdsa_sha2_{sn}_{base}_explicit')
o.append('\n'.join('#print axioms '+a for a in ax)); o.append('\nend MReduction\n')
open(OUT+'Explicit.lean','w').write('\n'.join(o))
